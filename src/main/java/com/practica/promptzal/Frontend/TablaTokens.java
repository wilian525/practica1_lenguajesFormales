    private DefaultTableModel modeloTabla;
    private JScrollPane scrollTokens;

    public TablaTokens() {
        configurarVentana();
        crearComponentes();
    }

    private void configurarVentana() {
        setTitle("Tokens");
        setClosable(true);
        setIconifiable(true);
        setMaximizable(true);
        setResizable(true);

        setSize(720, 350);
        setLayout(new BorderLayout());
    }

    private void crearComponentes() {
        modeloTabla = new DefaultTableModel(
                new Object[][]{},
                new String[]{
                    "No.",
                    "Lexema",
                    "Tipo",
                    "Fila",
                    "Columna"
                }
        ) {
            @Override
            public boolean isCellEditable(
                    int fila,
                    int columna) {

                return false;
            }
        };

        tablaTokens = new JTable(modeloTabla);

        tablaTokens.setFillsViewportHeight(true);
        tablaTokens.setAutoCreateRowSorter(true);

        scrollTokens = new JScrollPane(tablaTokens);

        add(
                scrollTokens,
                BorderLayout.CENTER
        );
    }

    public void cargarTokens(
            ArrayList<Token> tokens) {

        limpiar();

        if (tokens == null) {
            return;
        }

        for (Token token : tokens) {

            modeloTabla.addRow(
                    new Object[]{
                        token.getNumero(),
                        token.getLexema(),
                        token.getTipo().name(),
                        token.getFila(),
                        token.getColumna()
                    }
            );
        }
    }

    public void limpiar() {
        modeloTabla.setRowCount(0);
    }

    public JTable getTablaTokens() {
        return tablaTokens;
    }


